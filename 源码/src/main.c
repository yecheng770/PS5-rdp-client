int main(int argc, char **argv)
{
    (void)argc; (void)argv;

    signal(SIGPIPE, SIG_IGN);

    int ui_rc = ui_init();
    printf("[psrdp] ui_init rc=%d ready=%d\n", ui_rc, ui_ready());

    mode_load();
    int rc = display_init();
    if (g_rc_output == 0 && g_output.full_width && g_output.full_height)
        snprintf(g_output_label, sizeof(g_output_label), "PS5 output %ux%u",
                 g_output.full_width, g_output.full_height);
    size_t label_len = strlen(g_output_label);
    if (rc == 0)
        snprintf(g_output_label + label_len, sizeof(g_output_label) - label_len,
                 " / App buffer %dx%d%s", g_disp_w, g_disp_h,
                 g_output_fallback ? " (fallback)" : "");
    else
        snprintf(g_output_label + label_len, sizeof(g_output_label) - label_len,
                 " / App display failed (%d)", rc);
    printf("[psrdp] %s rc=%d pane=%ux%u layout=%s\n", g_output_label, rc,
           g_output.pane_width, g_output.pane_height, g_mode_name[g_mode]);

    conf_load();
    {
        int w,h;
        if (!res_split(g_cfg.res,&w,&h))
            snprintf(g_cfg.res,sizeof(g_cfg.res),"1920x1080");
        else
            snprintf(g_cfg.res,sizeof(g_cfg.res),"%dx%d",w,h);
    }
    g_res_sel = g_saved_custom ? RES_COUNT : res_index(g_cfg.res);
    custom_load();
    {
        int in_rc = input_init();
        printf("[psrdp] input_init rc=%d pad=%d kbd=%d mouse=%d\n",
               in_rc, input_pad_count(), input_keyboard_handle(),
               input_mouse_source());
    }

    input_set_sink(&g_home_sink);

    int ls = -1;
    static const int ports[] = { 8081, 8082, 8083, 18081, 28081 };
    char bind_note[384];
    bind_note[0] = 0;

    /* The app sandbox creates sockets but refuses to bind them through libc
     * (EACCES, seen as bind=13 on every port). sceNet is the family the
     * system services bind with, so sceNet is brought up first and each port
     * is tried both ways. Whichever family binds decides how the accepted
     * connections are driven for the rest of the run. */
    int net_rc = sceNetInit();
    int pool_rc = sceNetPoolCreate("psrdp_http", 16 * 1024, 0);
    snprintf(bind_note + strlen(bind_note), sizeof(bind_note) - strlen(bind_note),
             "uid=%d euid=%d net=%d pool=%d ",
             (int)getuid(), (int)geteuid(), net_rc, pool_rc);

    for (size_t i = 0; i < sizeof(ports) / sizeof(ports[0]); ++i) {
        struct sockaddr_in a;
        memset(&a, 0, sizeof(a));
        a.sin_family = AF_INET;
        a.sin_port = htons((uint16_t)ports[i]);
        a.sin_addr.s_addr = htonl(INADDR_ANY);

        /* Path 1: plain libc, exactly how earlier builds tried it. */
        errno = 0;
        int s = socket(AF_INET, SOCK_STREAM, 0);
        if (s < 0) {
            snprintf(bind_note + strlen(bind_note),
                     sizeof(bind_note) - strlen(bind_note),
                     "%d:sock=%d(%d) ", ports[i], s, errno);
        } else {
            int one = 1;
            setsockopt(s, SOL_SOCKET, SO_REUSEADDR, &one, sizeof(one));
            errno = 0;
            if (bind(s, (struct sockaddr *)&a, sizeof(a)) != 0) {
                snprintf(bind_note + strlen(bind_note),
                         sizeof(bind_note) - strlen(bind_note),
                         "%d:bind=%d ", ports[i], errno);
            } else {
                errno = 0;
                if (listen(s, 8) != 0) {
                    snprintf(bind_note + strlen(bind_note),
                             sizeof(bind_note) - strlen(bind_note),
                             "%d:listen=%d ", ports[i], errno);
                } else {
                    fcntl(s, F_SETFL, fcntl(s, F_GETFL, 0) | O_NONBLOCK);
                    ls = s;
                    g_http_port = ports[i];
                    g_net_sce = 0;
                    snprintf(bind_note + strlen(bind_note),
                             sizeof(bind_note) - strlen(bind_note),
                             "%d:libc-ok ", ports[i]);
                    break;
                }
            }
            close(s);
        }

        /* Path 2: sceNet, the family the sandbox lets bind. */
        if (pool_rc < 0)
            continue;
        s = sceNetSocket("psrdp_http", AF_INET, SOCK_STREAM, 0);
        if (s < 0) {
            snprintf(bind_note + strlen(bind_note),
                     sizeof(bind_note) - strlen(bind_note),
                     "%d:snet=%d ", ports[i], s);
            continue;
        }
        {
            int one = 1;
            sceNetSetsockopt(s, NET_SOL_SOCKET, NET_SO_REUSEADDR, &one, sizeof(one));
        }
        int brc = sceNetBind(s, &a, sizeof(a));
        if (brc != 0) {
            snprintf(bind_note + strlen(bind_note),
                     sizeof(bind_note) - strlen(bind_note),
                     "%d:sbind=%d ", ports[i], brc);
            sceNetSocketClose(s);
            continue;
        }
        brc = sceNetListen(s, 8);
        if (brc != 0) {
            snprintf(bind_note + strlen(bind_note),
                     sizeof(bind_note) - strlen(bind_note),
                     "%d:slisten=%d ", ports[i], brc);
            sceNetSocketClose(s);
            continue;
        }
        {
            int one = 1;
            sceNetSetsockopt(s, NET_SOL_SOCKET, NET_SO_NBIO, &one, sizeof(one));
        }
        ls = s;
        g_http_port = ports[i];
        g_net_sce = 1;
        snprintf(bind_note + strlen(bind_note),
                 sizeof(bind_note) - strlen(bind_note),
                 "%d:sce-ok ", ports[i]);
        break;
    }
    {
        FILE *df = fopen("/data/psrdp_diag.txt", "a");
        if (df) {
            fprintf(df, "[display] v%s %s status=%d pane=%ux%u register=%d flip=%d fallback=%s\n",
                    PSRDP_VERSION, g_output_label, g_rc_output, g_output.pane_width,
                    g_output.pane_height, g_rc_register, g_rc_flip,
                    g_output_fallback ? g_output_fallback : "none");
            fprintf(df, "[http] listen fd=%d port=%d note=%s\n",
                    ls, g_http_port,
                    bind_note[0] ? bind_note : "all-bind-attempts-logged");
            char mouse[512];
            input_mouse_dump(mouse, sizeof(mouse));
            fprintf(df, "[input-at-start] %s\n", mouse);
            fclose(df);
        }
    }
    printf("[psrdp] http listen fd=%d port=%d note=%s\n", ls, g_http_port, bind_note);
    g_ls = ls;
    if (ls >= 0) {
        pthread_t th;
        int force_inline = getenv("PSRDP_INLINE_HTTP") != NULL;  /* host-test hook */
        if (!force_inline && pthread_create(&th, NULL, http_worker, NULL) == 0) {
            pthread_detach(th);
            g_http_threaded = 1;
        } else {
            printf("[psrdp] http serving inline (thread unavailable)\n");
            g_http_threaded = 0;
        }
    }

    struct timespec t0, t1, tf;
    unsigned live_samples = 0;
    unsigned long long live_report_at = 0;
    double live_max_ms = 0.0;
    uint64_t input_poll_max_us = 0;
    uint64_t fps_frames = 0;
    rdp_phase last_phase = RDP_IDLE;
    char last_res[sizeof(g_cfg.res)] = {0};
    int last_devices = -1;
    clock_gettime(CLOCK_MONOTONIC, &t0);

    for (;;) {
        g_ticks++;
        clock_gettime(CLOCK_MONOTONIC, &tf);

        input_frame f;
        memset(&g_home_keys, 0, sizeof(g_home_keys));
        input_poll(&f);
        int devices = input_mouse_connected() | (input_keyboard_connected() << 1);
        if (devices != last_devices) {
            last_devices = devices;
            menu_invalidate();
        }
        if (g_live && live_samples < 12) {
            uint64_t start = (uint64_t)tf.tv_sec * 1000000 + (uint64_t)tf.tv_nsec / 1000;
            uint64_t elapsed = monotonic_us() - start;
            if (elapsed > input_poll_max_us)
                input_poll_max_us = elapsed;
        }

        rdp_state st;
        psrdp_get_state(&st);
        if (strcmp(last_res, g_cfg.res) != 0) {
            snprintf(last_res, sizeof(last_res), "%s", g_cfg.res);
            if (g_custom_axis < 0) {
                g_res_sel = g_saved_custom ? RES_COUNT : res_index(last_res);
                custom_load();
            }
            menu_invalidate();
        }
        if (st.phase != last_phase) {
            last_phase = st.phase;
            menu_invalidate();
            if (st.phase == RDP_LIVE && live_samples == 0)
                live_report_at = (unsigned long long)tf.tv_sec + 5;
        }

        int paced = 0;
        if (rc == 0) {
            if (st.phase == RDP_LIVE) {
                if (!g_live)
                    live_enter();
                live_input(&f);
            } else if (g_live) {
                live_leave();
            }

            if (g_live) {
                int back = (g_front < 0) ? 0 : 1 - g_front;
                g_drawn_blit_us = 0;
                if (g_session_menu.open) {
                    draw_session_menu(g_buf[back]);
                    g_desktop_buffer[back] = 0;
                } else if (!draw_rdp_picture(back)) {
                    g_desktop_buffer[back] = 0;
                    uint32_t *lin = ui_lin_get(g_disp_w, g_disp_h);
                    if (lin) {
                        ui_surface s;
                        s.width = g_disp_w; s.height = g_disp_h;
                        s.pitch = g_disp_w; s.pixels = lin;
                        ui_begin(&s);
                        ui_clear(0x000E1116u);
                        ui_draw_banner(ui_localize("Waiting for the first frame"), NULL, NULL);
                        present_linear(g_buf[back], lin, g_disp_w, g_disp_h);
                    }
                } else {
                    g_cursor_rect[back] = draw_local_pointer(g_buf[back]);
                }
                paced = display_present(back);
                if (g_rc_flip == 0 && g_drawn_blit_us && live_samples < 12) {
                    uint64_t elapsed = monotonic_us() - g_drawn_blit_us;
                    if (elapsed > g_blit_flip_max_us)
                        g_blit_flip_max_us = elapsed;
                }
                g_frames++;
                fps_frames++;
            } else {
                pthread_mutex_lock(&g_config_mutex);
                f.up |= g_home_keys.up;
                f.down |= g_home_keys.down;
                f.left |= g_home_keys.left;
                f.right |= g_home_keys.right;
                f.confirm |= g_home_keys.confirm;
                f.cancel |= g_home_keys.cancel;
                f.square |= g_home_keys.square;
                f.triangle |= g_home_keys.triangle;
                f.any |= g_home_keys.any;
                home_click(&f);
                if (f.any) menu_invalidate();
                menu_input(&f);
                int back = (g_front < 0) ? 0 : 1 - g_front;
                if (g_menu_stale[back] || g_desktop_buffer[back]) {
                    draw_menu(g_buf[back]);
                    g_menu_stale[back] = 0;
                    g_desktop_buffer[back] = 0;
                }
                pthread_mutex_unlock(&g_config_mutex);
                paced = display_present(back);
                g_frames++;
                fps_frames++;
            }
        } else {
            sceKernelUsleep(100000);
        }

        if (g_ls >= 0 && g_http_threaded == 0)
            http_poll_once(g_ls);   /* never loops, so the frame pacing holds */

        /* Successful vblank already paces scanout. Sleep only on fallback. */
        {
            clock_gettime(CLOCK_MONOTONIC, &t1);
            long used = (long)(t1.tv_sec - tf.tv_sec) * 1000000L
                      + (long)(t1.tv_nsec - tf.tv_nsec) / 1000L;
            long rest = 16666L - used;
            if (g_live && live_samples < 12) {
                unsigned long long now = (unsigned long long)tf.tv_sec;
                double work_ms = (double)used / 1000.0;
                if (work_ms > live_max_ms)
                    live_max_ms = work_ms;
                if (now >= live_report_at) {
                    char mouse[512];
                    input_mouse_dump(mouse, sizeof(mouse));
                    FILE *df = fopen("/data/psrdp_diag.txt", "a");
                    if (df) {
                        fprintf(df, "[live-sample] v%s fps=%.1f loop_work_max_ms=%.1f "
                                "poll_max_ms=%.2f mouse_send_max_ms=%.2f blit_to_vblank_max_ms=%.2f %s\n",
                                PSRDP_VERSION, g_fps, live_max_ms,
                                input_poll_max_us / 1000.0, g_pointer_send_max_us / 1000.0,
                                g_blit_flip_max_us / 1000.0, mouse);
                        fclose(df);
                    }
                    ++live_samples;
                    live_report_at = now + 5;
                    live_max_ms = 0.0;
                    input_poll_max_us = g_pointer_send_max_us = g_blit_flip_max_us = 0;
                }
            }
            if (!paced)
                sceKernelUsleep(rest > 1000 ? (unsigned int)rest : 500u);
        }

        if (fps_frames >= 30) {
            clock_gettime(CLOCK_MONOTONIC, &t1);
            double dt = (double)(t1.tv_sec - t0.tv_sec)
                      + (double)(t1.tv_nsec - t0.tv_nsec) / 1e9;
            if (dt > 0.5) {
                g_fps = (double)fps_frames / dt;
                fps_frames = 0;
                t0 = t1;
            }
        }
    }
}
