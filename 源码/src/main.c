/*
 * PSrdp - native RDP client for the PS5.
 *
 * Two threads:
 *   - the display thread owns VideoOut, the on-screen UI (psrdp_ui.c) and
 *     forwards pad / keyboard / mouse events to the session (rdp.c)
 *   - the HTTP thread serves the config page and the diagnostics trace
 *
 * rdp.c owns the FreeRDP session and decodes into g_picture; this file owns
 * the PS5 scanout: tiling, clflush, flips, and the pages that sit on top.
 *
 * Scanout remains at the verified 1080p size. Remote desktops from 720p
 * through 2160p are scaled into that surface without re-registering it.
 */

