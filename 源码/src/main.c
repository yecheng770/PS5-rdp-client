/* Handle at most one pending connection: returns 1 if a request was served.
 * It never loops, so the display loop may call it without risking a stall. */
static int http_poll_once(int ls)
{
    int fd = net_accept(ls);
    if (fd < 0)
        return 0;

    net_conn_nonblocking(fd);

    /* Bounded spin for the request head: ~2 s. A half-open client costs at
     * most that, and never blocks the frame loop or the HTTP thread. */
    char buf[2048];
    long n = 0;
    for (int spin = 0; spin < 200; ++spin) {
        n = net_recv(fd, buf, sizeof(buf) - 1, 0);
        if (n > 0 || n == 0)
            break;
        sceKernelUsleep(10000);
    }

    if (n > 0) {
        buf[n] = 0;
        char *hdrs_end = strstr(buf, "\r\n\r\n");
        const char *body = hdrs_end ? hdrs_end + 4 : "";
        if (hdrs_end) {
            /* If Content-Length runs past this read, pull the rest in. */
            char *cl = strstr(buf, "Content-Length:");
            if (cl) {
                long want = strtol(cl + 15, NULL, 10);
                long have = (long)(n - (body - buf));
                int idle = 0;
                while (have < want && have < (long)sizeof(buf) - 1) {
                    long m = net_recv(fd, buf + n, sizeof(buf) - 1 - (size_t)n, 0);
                    if (m <= 0) {
                        if (m < 0 && ++idle < 20) {
                            sceKernelUsleep(10000);
                            continue;
                        }
                        break;
                    }
                    idle = 0;
                    n += m;
                    have += m;
                    buf[n] = 0;
                }
                body = strstr(buf, "\r\n\r\n") + 4;
            }
        }
        serve_request(fd, buf, body);
    }
    net_close(fd);
    return 1;
}

static int g_ls = -1;

static void *http_worker(void *arg)
{
    (void)arg;
    for (;;) {
        if (!http_poll_once(g_ls))
            sceKernelUsleep(10000);
    }
    return NULL;
}

