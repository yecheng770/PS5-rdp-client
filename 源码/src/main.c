static void pointer_send(void)
{
    uint64_t start = monotonic_us();
    if (rdp_send_mouse(remote_x(), remote_y(), g_buttons)) {
        uint64_t elapsed = monotonic_us() - start;
        if (elapsed > g_pointer_send_max_us)
            g_pointer_send_max_us = elapsed;
    }
}
static void pointer_apply_motion(void)
{
    if (!g_ptr_acc_x && !g_ptr_acc_y) return;
    g_ptr_x += g_ptr_acc_x; g_ptr_y += g_ptr_acc_y;
    g_ptr_acc_x = g_ptr_acc_y = 0;
    pointer_clamp();
    pointer_send();
}

static void sink_key(int down, unsigned short code)
{
    if (rdp_send_key(down, (int)code) && code < sizeof(g_remote_keys))
        g_remote_keys[code] = down ? 1 : 0;
}

/* Mouse counts are converted to a fraction of the displayed area.
 * At 1080p, one count moves 1.6 pixels. Carry the fraction between polls. */
static int g_mouse_frac_x, g_mouse_frac_y;
static int mouse_motion(int counts, int extent, int reference, int *remainder)
{
    int64_t units = (int64_t)counts * extent * 8 + *remainder;
    int denominator = 5 * reference;
    *remainder = (int)(units % denominator);
    return (int)(units / denominator);
}

static void sink_mouse_rel(int dx, int dy)
{
    g_ptr_acc_x += mouse_motion(dx, g_disp_w, 1920, &g_mouse_frac_x);
    g_ptr_acc_y += mouse_motion(dy, g_disp_h, 1080, &g_mouse_frac_y);
}

static void sink_mouse_button(int button, int down)
{
    if (button < 0 || button >= (int)sizeof(g_button_hold)) return;
    pointer_apply_motion();
    int bit = 1 << button;
    if (down) {
        if (g_button_hold[button] == 0) g_buttons |= bit;
        if (g_button_hold[button] < 255) ++g_button_hold[button];
    } else {
        if (g_button_hold[button]) --g_button_hold[button];
        if (g_button_hold[button] == 0) g_buttons &= ~bit;
    }
    pointer_send();
}

static void sink_mouse_wheel(int notches)
{
    pointer_apply_motion();
    rdp_send_wheel(remote_x(), remote_y(), notches);
}

static const input_sink g_remote_sink = {
    sink_key, sink_mouse_rel, sink_mouse_button, sink_mouse_wheel
};

static void remote_input_pause(void)
{
    /* Detach before drawing a local menu; release remote state while the
     * connection is still live. Discard pending movement and wheel events. */
    input_set_sink(NULL);
    for (unsigned i=1; i<sizeof(g_remote_keys); ++i) {
        if (g_remote_keys[i]) rdp_send_key(0,(int)i);
        g_remote_keys[i]=0;
    }
    g_buttons=0;
    g_mouse_frac_x = g_mouse_frac_y = 0;
    memset(g_button_hold,0,sizeof(g_button_hold));
    g_ptr_acc_x=g_ptr_acc_y=g_wheel_acc=0;
    pointer_send();
}

