/* HTTP transport: libc or sceNet                                      */
/* ------------------------------------------------------------------ */

/* Decided once when the listener comes up. A sceNet id is not a libc file
 * descriptor, so every call on an accepted connection has to go through the
 * same family that bound the listener. */
static int g_net_sce;

static int net_accept(int ls)
{
    struct sockaddr_in peer;
    if (g_net_sce) {
        unsigned plen = sizeof(peer);
        return sceNetAccept(ls, &peer, &plen);
    }
    {
        socklen_t plen = sizeof(peer);
        return accept(ls, (struct sockaddr *)&peer, &plen);
    }
}

static long net_recv(int fd, void *buf, size_t len, int flags)
{
    if (g_net_sce) {
        unsigned alen = 0;
        return sceNetRecvfrom(fd, buf, len, flags, NULL, &alen);
    }
    return (long)recv(fd, buf, len, flags);
}

static void net_close(int fd)
{
    if (g_net_sce)
        sceNetSocketClose(fd);
    else
        close(fd);
}

/* The listener runs non-blocking so the display loop never parks inside
 * accept(). Connections are non-blocking too: the request is drained by a
 * short bounded spin instead, so a half-open client can never hold the HTTP
 * thread - or, on the inline path, a frame. */
static void net_conn_nonblocking(int fd)
{
    if (g_net_sce) {
        int one = 1;
        sceNetSetsockopt(fd, NET_SOL_SOCKET, NET_SO_NBIO, &one, sizeof(one));
        return;
    }
    {
        int fl = fcntl(fd, F_GETFL, 0);
        if (fl >= 0)
            fcntl(fd, F_SETFL, fl | O_NONBLOCK);
    }
}

static int send_all(int fd, const char *buf, size_t len)
{
    while (len > 0) {
        long n = g_net_sce ? (long)sceNetSend(fd, buf, len, 0)
                           : (long)send(fd, buf, len, 0);
        if (n <= 0)
            return -1;
        buf += n;
        len -= (size_t)n;
    }
    return 0;
}

static int session_alive(void)
{
    rdp_state st;
    psrdp_get_state(&st);
    return st.running || st.phase == RDP_LIVE || st.phase == RDP_CONNECTING;
}

/* Menu-side start: clears the decoder surface first, exactly like the page. */
static void session_start(void)
{
    rdp_state st;
    psrdp_get_state(&st);
    if (st.running)
        return;

    if (!valid_host(g_cfg.host) || g_cfg.port < 1 || g_cfg.port > 65535) {
        psrdp_note("Enter a host and a valid port in Connection settings");
        return;
    }
    int rc = rdp_start();
    if (rc == 0)
        psrdp_note("start requested (thread up)");
    else if (rc == -1)
        psrdp_note("start refused: running=%d phase=%d",
                   st.running, (int)st.phase);
    else if (rc == -2)
        psrdp_note("start failed: CreateEvent rc=-2");
    else
        psrdp_note("start failed: pthread_create rc=-3");
}

