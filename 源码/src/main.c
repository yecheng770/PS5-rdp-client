static int hexval(int c)
{
    if (c >= '0' && c <= '9') return c - '0';
    if (c >= 'a' && c <= 'f') return c - 'a' + 10;
    if (c >= 'A' && c <= 'F') return c - 'A' + 10;
    return -1;
}

#ifndef PSRDP_CONF
#define PSRDP_CONF "/data/psrdp.conf"
#endif
#define PROFILE_LIMIT 3

typedef struct {
    char host[sizeof(g_cfg.host)], user[sizeof(g_cfg.user)], pass[sizeof(g_cfg.pass)];
    int port, remember;
} connection_profile;

static connection_profile g_profiles[PROFILE_LIMIT];
static int g_profile_count, g_remember;
static pthread_mutex_t g_config_mutex = PTHREAD_MUTEX_INITIALIZER;

static connection_profile current_profile(void)
{
    connection_profile profile = {0};
    strcpy(profile.host, g_cfg.host);
    strcpy(profile.user, g_cfg.user);
    strcpy(profile.pass, g_cfg.pass);
    profile.port = g_cfg.port;
    profile.remember = g_remember;
    return profile;
}

static int same_target(const connection_profile *a, const connection_profile *b)
{
    return a->port == b->port && !strcmp(a->host, b->host) && !strcmp(a->user, b->user);
}

static void apply_profile(const connection_profile *profile)
{
    strcpy(g_cfg.host, profile->host);
    strcpy(g_cfg.user, profile->user);
    strcpy(g_cfg.pass, profile->pass);
    g_cfg.port = profile->port;
    g_remember = profile->remember;
}

static void push_profile(connection_profile profile)
{
    int index = 0;
    while (index < g_profile_count && !same_target(&profile, &g_profiles[index])) ++index;
    if (index == g_profile_count && g_profile_count < PROFILE_LIMIT) ++g_profile_count;
    if (index == PROFILE_LIMIT) --index;
    if (!profile.remember) memset(profile.pass, 0, sizeof(profile.pass));
    memmove(g_profiles + 1, g_profiles, (size_t)index * sizeof(profile));
    g_profiles[0] = profile;
}

static int parse_port(const char *text)
{
    int port = psrdp_parse_dimension(&text, 65535);
    return *text || port < 1 ? 0 : port;
}

static int valid_host(const char *s)
{
    if (!*s || strstr(s, "://")) return 0;
    for (; *s; ++s) {
        unsigned char c = (unsigned char)*s;
        if (c <= ' ' || c == 127 || strchr("/\\?#", c)) return 0;
    }
    return 1;
}

/* Hex keeps profile fields round-trippable, including delimiters and UTF-8.
 * This is encoding, not encryption. Only write passwords opted in locally. */
static void conf_write_field(FILE *f, const char *s)
{
    while (*s) fprintf(f, "%02x", (unsigned char)*s++);
}

static int conf_read_field(char *out, size_t cap, const char *line)
{
    size_t len = strlen(line);
    if (len % 2 || len / 2 >= cap) return 0;
    for (size_t i = 0; i < len; i += 2) {
        int a = hexval(line[i]), b = hexval(line[i+1]);
        if (a < 0 || b < 0 || (!a && !b)) return 0;
        out[i/2] = (char)(a * 16 + b);
    }
    out[len/2] = 0;
    return 1;
}

/* Caller holds g_config_mutex after startup. Atomic replacement preserves
 * the previous configuration if a write is interrupted or fails. */
static int g_ui_language = UI_ZH;
static int g_saved_custom;

static int conf_save(void)
{
    const char *temp = PSRDP_CONF ".tmp";
    int fd = open(temp, O_CREAT | O_EXCL | O_WRONLY, 0600);
    if (fd < 0) return 0;
    FILE *f = fdopen(fd, "w");
    if (!f) { close(fd); unlink(temp); return 0; }
    fprintf(f, "res=%s\ndesktop_scale=%u\nlanguage=%s\n", g_cfg.res,
            g_cfg.desktop_scale, ui_language_codes[g_ui_language]);
    if (g_saved_custom) fputs("resolution_mode=custom\n", f);
    for (int i = 0; i < g_profile_count; ++i) {
        const connection_profile *profile = &g_profiles[i];
        fprintf(f, "profile=%d,%d,", profile->port, profile->remember);
        conf_write_field(f, profile->host); fputc(',', f);
        conf_write_field(f, profile->user); fputc(',', f);
        if (profile->remember) conf_write_field(f, profile->pass);
        fputc('\n', f);
    }
    int ok = fflush(f) == 0 && !ferror(f) && fsync(fd) == 0;
    if (fclose(f) != 0) ok = 0;
    if (ok && rename(temp, PSRDP_CONF) == 0) return 1;
    unlink(temp);
    return 0;
}

static int conf_read_profile(char *line, connection_profile *profile)
{
    char *fields[5] = {line};
    for (int i = 1; i < 5; ++i) {
        char *comma = strchr(fields[i-1], ',');
        if (!comma) return 0;
        *comma = 0;
        fields[i] = comma + 1;
    }
    profile->port = parse_port(fields[0]);
    profile->remember = !strcmp(fields[1], "1");
    return profile->port && conf_read_field(profile->host, sizeof(profile->host), fields[2]) &&
           valid_host(profile->host) && conf_read_field(profile->user, sizeof(profile->user), fields[3]) &&
           (!profile->remember || conf_read_field(profile->pass, sizeof(profile->pass), fields[4]));
}

static void conf_load(void)
{
    char line[576];
    unlink(PSRDP_CONF ".tmp");
    FILE *f = fopen(PSRDP_CONF, "r");
    if (!f) return;
    connection_profile original = current_profile(), legacy = original;
    int legacy_seen = 0;
    while (fgets(line, sizeof(line), f)) {
        line[strcspn(line, "\r\n")] = 0;
        if (!strncmp(line, "host=", 5)) {
            snprintf(legacy.host, sizeof(legacy.host), "%.*s", (int)sizeof(legacy.host)-1, line + 5);
            legacy_seen = 1;
        } else if (!strncmp(line, "port=", 5)) {
            int port = parse_port(line + 5);
            if (port) legacy.port = port;
        } else if (!strncmp(line, "user=", 5)) {
            snprintf(legacy.user, sizeof(legacy.user), "%.*s", (int)sizeof(legacy.user)-1, line + 5);
        } else if (!strncmp(line, "res=", 4)) {
            int w, h;
            if (psrdp_resolution(line+4, &w, &h)) snprintf(g_cfg.res, sizeof(g_cfg.res), "%dx%d", w, h);
        } else if (!strcmp(line, "resolution_mode=custom")) {
            g_saved_custom = 1;
        } else if (!strncmp(line, "language=", 9)) {
            for (int i = 0; i < UI_LANG_COUNT; ++i)
                if (!strcmp(line + 9, ui_language_codes[i])) g_ui_language = i;
        } else if (!strncmp(line, "desktop_scale=", 14)) {
            int scale = parse_port(line + 14);
            for (int i = 0; i < SCALE_COUNT; ++i)
                if (scale == (int)g_scale_options[i]) g_cfg.desktop_scale = g_scale_options[i];
        } else if (!strncmp(line, "profile=", 8) && g_profile_count < PROFILE_LIMIT) {
            connection_profile profile = {0};
            if (conf_read_profile(line + 8, &profile)) g_profiles[g_profile_count++] = profile;
        }
    }
    fclose(f);
    if (g_profile_count) apply_profile(&g_profiles[0]);
    else if (legacy_seen && valid_host(legacy.host)) {
        if (!same_target(&legacy, &original)) memset(legacy.pass, 0, sizeof(legacy.pass));
        apply_profile(&legacy);
        push_profile(legacy);
    }
}

static int save_connection(connection_profile profile)
{
    connection_profile previous = current_profile();
    connection_profile history[PROFILE_LIMIT];
    int count = g_profile_count;
    memcpy(history, g_profiles, sizeof(history));
    apply_profile(&profile);
    push_profile(profile);
    if (conf_save()) return 1;
    apply_profile(&previous);
    memcpy(g_profiles, history, sizeof(history));
    g_profile_count = count;
    return 0;
}

static void urldecode(const char *src, char *dst, size_t cap)
{
    size_t o = 0;
    while (*src && o + 1 < cap) {
        if (*src == '+') {
            dst[o++] = ' ';
            src++;
        } else if (*src == '%' && hexval(src[1]) >= 0 && hexval(src[2]) >= 0) {
            dst[o++] = (char)((hexval(src[1]) << 4) | hexval(src[2]));
            src += 3;
        } else {
            dst[o++] = *src++;
        }
    }
    dst[o] = 0;
}

static void form_get(const char *body, const char *key, char *out, size_t cap)
{
    char pat[48];
    size_t klen = strlen(key);
    snprintf(pat, sizeof(pat), "%s=", key);

    const char *p = body;
    while (p && *p) {
        if (strncmp(p, pat, klen + 1) == 0) {
            const char *v = p + klen + 1;
            const char *e = strchr(v, '&');
            size_t n = e ? (size_t)(e - v) : strlen(v);
            char tmp[256];
            if (n >= sizeof(tmp)) n = sizeof(tmp) - 1;
            memcpy(tmp, v, n);
            tmp[n] = 0;
            urldecode(tmp, out, cap);
            return;
        }
        p = strchr(p, '&');
        if (p) p++;
    }
}

