static void connection_input(const input_frame *f)
{
    if (g_key_open) {
        int x = g_key_index % UI_KEY_COLS, y = g_key_index / UI_KEY_COLS;
        x = (x + UI_KEY_COLS + f->right - f->left) % UI_KEY_COLS;
        y = (y + UI_KEY_ROWS + f->down - f->up) % UI_KEY_ROWS;
        g_key_index = y * UI_KEY_COLS + x;
        if (f->r1) g_key_page = (g_key_page + 1) % UI_KEY_PAGES;
        if (f->l1) g_key_page = (g_key_page + UI_KEY_PAGES - 1) % UI_KEY_PAGES;
        size_t len = strlen(g_entry), cap;
        char *field = connection_field(g_connection_focus, &cap);
        if (f->square && len) {
            do { --len; } while (len && ((unsigned char)g_entry[len] & 0xc0) == 0x80);
            g_entry[len] = 0;
        }
        if (f->cancel) g_key_open = 0;
        else if (f->triangle) {
            strcpy(field, g_entry);
            g_key_open = 0;
        } else if (f->confirm && len + 1 < cap) {
            char c = ui_keyboard_char(g_key_page, g_key_index);
            if (g_connection_focus != UI_CONN_PORT || (c >= '0' && c <= '9')) {
                g_entry[len] = c;
                g_entry[len+1] = 0;
            }
        }
        if (!g_key_open) memset(g_entry, 0, sizeof(g_entry));
        return;
    }
    if (f->cancel) { g_connection_open = 0; return; }
    if (f->up || f->down) {
        g_connection_focus = (g_connection_focus + UI_CONN_COUNT + f->down - f->up) % UI_CONN_COUNT;
        g_connection_message = NULL;
    }
    if (g_connection_focus == UI_CONN_HISTORY && g_profile_count) {
        g_history_selected = (g_history_selected + g_profile_count + f->right - f->left) % g_profile_count;
        if (f->confirm) {
            begin_profile_edit(g_profiles[g_history_selected]);
            g_connection_message = "Loaded into editor. Select Save to use this connection.";
        }
        return;
    }
    if (g_connection_focus == UI_CONN_REMEMBER && (f->confirm || f->left || f->right)) {
        g_connection_draft.remember = !g_connection_draft.remember;
        return;
    }
    if (!f->confirm) return;
    if (g_connection_focus <= UI_CONN_PASS) {
        size_t capacity;
        strcpy(g_entry, connection_field(g_connection_focus, &capacity));
        g_key_open = 1;
        g_key_index = g_key_page = 0;
    } else if (g_connection_focus == UI_CONN_SAVE) {
        g_connection_draft.port = parse_port(g_connection_port);
        if (!valid_host(g_connection_draft.host)) g_connection_message = "Enter a hostname or IP address.";
        else if (!g_connection_draft.port) g_connection_message = "Port must be between 1 and 65535.";
        else if (!save_connection(g_connection_draft)) g_connection_message = "Could not save connection settings.";
        else {
            psrdp_note("Connection settings saved");
            g_connection_open = 0;
            g_home_focus = UI_HOME_CONNECT;
        }
    }
}
