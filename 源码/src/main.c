/* The LUT maps one 512x128 window and is a clean permutation of 0..65535,
 * so the swizzle inside a window is right; all that is left unknown is where
 * each window starts in memory. That cannot be read off the LUT, so every
 * plausible answer is compiled in and the winner is remembered next to the
 * app as /data/psrdp_mode.txt. Without that file the compact packing is the
 * default - the layout the first on-hardware run locked in. */
enum {
    MODE_COMPACT = 0,    /* band stride g_disp_w, windows packed      */
    MODE_PAD4,           /* band stride 4*512 (2048), windows padded  */
    MODE_COL9,           /* column-major, 9 bands per column          */
    MODE_COL12,          /* column-major, 12 bands per column         */
    MODE_LIN1920,        /* not tiled at all, 1920 pitch              */
    MODE_LIN2048,        /* not tiled, 2048 pitch                     */
    MODE_COUNT
};

static const char *const g_mode_name[MODE_COUNT] = {
    "compact", "padded tiles", "col-major 9", "col-major 12",
    "linear 1920", "linear 2048"
};

static int g_mode = MODE_COMPACT;

static inline size_t block_base(int c, int b)
{
    switch (g_mode) {
    case MODE_COMPACT:
        return (size_t)b * (size_t)g_disp_w * PS5_TILE_HEIGHT
             + (size_t)c * PS5_TILE_SIZE;
    case MODE_PAD4:
        return ((size_t)b * g_tiles_per_col + (size_t)c) * PS5_TILE_SIZE;
    case MODE_COL9:
        return (size_t)c * (g_tile_rows * PS5_TILE_SIZE)
             + (size_t)b * PS5_TILE_SIZE;
    default:
        return (size_t)c * (12u * PS5_TILE_SIZE)
             + (size_t)b * PS5_TILE_SIZE;
    }
}

/* Offset of (x,y) inside the surface, in pixels. */
static inline size_t pix_off(int x, int y)
{
    if (g_mode == MODE_LIN1920) return (size_t)y * g_disp_w + (size_t)x;
    if (g_mode == MODE_LIN2048) return (size_t)y * 2048u + (size_t)x;
    return block_base(x >> 9, y >> 7)
         + (size_t)PS5_tilemap[y & (PS5_TILE_HEIGHT - 1)][x & (PS5_TILE_WIDTH - 1)];
}

static void fill_row_span(uint32_t *surf, int y, int x0, int n, uint32_t color)
{
    if (g_mode == MODE_LIN1920 || g_mode == MODE_LIN2048) {
        uint32_t *p = surf + pix_off(x0, y);
        for (int i = 0; i < n; ++i)
            p[i] = color;
        return;
    }

    const unsigned short *lut = PS5_tilemap[y & (PS5_TILE_HEIGHT - 1)];
    while (n > 0) {
        int in_tile = PS5_TILE_WIDTH - (x0 & (PS5_TILE_WIDTH - 1));
        int take = n < in_tile ? n : in_tile;
        uint32_t *tile = surf + block_base(x0 >> 9, y >> 7);
        int k = x0 & (PS5_TILE_WIDTH - 1);
        for (int i = 0; i < take; ++i)
            tile[lut[k + i]] = color;
        x0 += take;
        n  -= take;
    }
}

static void clear_surface(uint32_t *surf, uint32_t color)
{
    for (int y = 0; y < g_disp_h; ++y)
        fill_row_span(surf, y, 0, g_disp_w, color);
}

static void flush_rect(uint32_t *surf, int x, int y, int w, int h);

/* ------------------------------------------------------------------ */
/* Linear -> tiled bridge for the UI layer                            */
/*                                                                     */
/* psrdp_ui.c addresses pixels row-major (pixels + y*pitch + x). The   */
/* scanout buffer is tiled, so anything drawn straight into g_buf[]    */
/* comes out as vertical bands of colour. The menu and the banner are  */
/* therefore drawn into a plain CPU buffer first and copied here.      */
/* ------------------------------------------------------------------ */
static uint32_t *ui_lin_get(int w, int h)
{
    return w == g_disp_w && h == g_disp_h ? g_ui_lin : NULL;
}

/* Copy one row of w pixels from a linear frame into scanout row y. */
static void copy_row_tiled(uint32_t *surf, int y, int x0, const uint32_t *src, int w)
{
    if (g_mode == MODE_LIN1920) {
        memcpy(surf + pix_off(x0, y), src + x0, (size_t)w * 4u);
        return;
    }
    if (g_mode == MODE_LIN2048) {
        memcpy(surf + pix_off(x0, y), src + x0, (size_t)w * 4u);
        return;
    }

    const unsigned short *lut = PS5_tilemap[y & (PS5_TILE_HEIGHT - 1)];
    int n = w;
    while (n > 0) {
        int off = x0 & (PS5_TILE_WIDTH - 1);
        int in_tile = PS5_TILE_WIDTH - off;
        int take = n < in_tile ? n : in_tile;
        uint32_t *tile = surf + block_base(x0 >> 9, y >> 7);
        for (int i = 0; i < take; ++i)
            tile[lut[off + i]] = src[x0 + i] & 0x00ffffffu;
        x0 += take;
        n  -= take;
    }
}

/* Replace the whole scanout surface with a linear frame, then flush. */
static void present_linear(uint32_t *surf, const uint32_t *lin, int w, int h)
{
    for (int y = 0; y < h; ++y)
        copy_row_tiled(surf, y, 0, lin + (size_t)y * (size_t)w, w);
    flush_rect(surf, 0, 0, w, h);
}


/* The worker updates a linear picture. Track what each back buffer still
 * needs so a small RDP update never forces another full scanout copy. */
typedef struct { int x0, y0, x1, y1; } picture_rect;
static pthread_mutex_t g_picture_mutex = PTHREAD_MUTEX_INITIALIZER;
static int g_picture_ready;
static picture_rect g_picture_dirty[2], g_cursor_rect[2];
static int g_desktop_buffer[2];
/* All of these timestamps use the console's monotonic clock. */
static uint64_t g_pending_blit_us[2]; /* protected by g_picture_mutex */
static uint64_t g_drawn_blit_us, g_blit_flip_max_us, g_pointer_send_max_us;

static uint64_t monotonic_us(void)
{
    struct timespec now;
    clock_gettime(CLOCK_MONOTONIC, &now);
    return (uint64_t)now.tv_sec * 1000000 + (uint64_t)now.tv_nsec / 1000;
}

static int rect_empty(picture_rect r) { return r.x0 >= r.x1 || r.y0 >= r.y1; }

static picture_rect rect_union(picture_rect a, picture_rect b)
{
    if (rect_empty(a)) return b;
    if (rect_empty(b)) return a;
    return (picture_rect){a.x0 < b.x0 ? a.x0 : b.x0, a.y0 < b.y0 ? a.y0 : b.y0,
                          a.x1 > b.x1 ? a.x1 : b.x1, a.y1 > b.y1 ? a.y1 : b.y1};
}

void psrdp_picture_reset(void)
{
    pthread_mutex_lock(&g_picture_mutex);
    g_picture_ready = 0;
    g_pending_blit_us[0] = g_pending_blit_us[1] = 0;
    pthread_mutex_unlock(&g_picture_mutex);
}

/* Lower bound of the output pixels sampling source coordinate src or later.
 * Using the same mapping as the copy also covers non-integral scale ratios. */
static int output_bound(int src, int dst_size, int src_size)
{
    int lo = 0, hi = dst_size;
    while (lo < hi) {
        int mid = lo + (hi-lo)/2;
        if (psrdp_map_coordinate(mid, dst_size, src_size) < src) lo = mid+1;
        else hi = mid;
    }
    return lo;
}

void psrdp_blit(const void *pix, int w, int h, int pitch,
                int x0, int y0, int x1, int y1)
{
    if (!pix || w <= 0 || h <= 0 || w > PSRDP_REMOTE_MAX_W ||
        h > PSRDP_REMOTE_MAX_H || pitch < w*4 || x0 < 0 || y0 < 0 ||
        x1 > w || y1 > h || x0 >= x1 || y0 >= y1)
        return;
    const uint64_t received_at = monotonic_us();
    picture_rect r = {output_bound(x0, g_disp_w, w), output_bound(y0, g_disp_h, h),
                      output_bound(x1, g_disp_w, w), output_bound(y1, g_disp_h, h)};
    pthread_mutex_lock(&g_picture_mutex);
    int first = !g_picture_ready;
    if (first) r = (picture_rect){0, 0, g_disp_w, g_disp_h};
    if (w == g_disp_w && h == g_disp_h) {
        for (int y = r.y0; y < r.y1; ++y)
            memcpy(g_picture + (size_t)y * g_disp_w + r.x0,
                   (const uint8_t *)pix + (size_t)y * pitch + r.x0 * 4,
                   (size_t)(r.x1-r.x0)*4);
    } else {
        int xs[MAX_DISP_W];
        for (int x = r.x0; x < r.x1; ++x)
            xs[x] = psrdp_map_coordinate(x, g_disp_w, w);
        for (int y = r.y0; y < r.y1; ++y) {
            int sy = psrdp_map_coordinate(y, g_disp_h, h);
            const uint32_t *row = (const uint32_t *)((const uint8_t *)pix + (size_t)sy*pitch);
            for (int x = r.x0; x < r.x1; ++x)
                g_picture[(size_t)y * g_disp_w + x] = row[xs[x]];
        }
    }
    for (int i = 0; i < 2; ++i) {
        g_picture_dirty[i] = rect_union(g_picture_dirty[i], r);
        if (!rect_empty(r) && !g_pending_blit_us[i])
            g_pending_blit_us[i] = received_at;
    }
    g_picture_ready = 1;
    pthread_mutex_unlock(&g_picture_mutex);
    if (first) {
        char line[128];
        snprintf(line, sizeof(line), "Display path: decoded %dx%d -> PS5 buffer %dx%d (%s)",
                 w, h, g_disp_w, g_disp_h,
                 w == g_disp_w && h == g_disp_h ? "1:1" : "resampled");
        psrdp_diag_line(line);
    }
}

static void restore_picture_rect(uint32_t *surf, picture_rect r)
{
    if (rect_empty(r)) return;
    for (int y = r.y0; y < r.y1; ++y)
        copy_row_tiled(surf, y, r.x0, g_picture + (size_t)y * g_disp_w, r.x1-r.x0);
}

static void flush_picture_rect(uint32_t *surf, picture_rect r)
{
    if (!rect_empty(r)) flush_rect(surf, r.x0, r.y0, r.x1-r.x0, r.y1-r.y0);
}

static int draw_rdp_picture(int back)
{
    uint32_t *surf = g_buf[back];
    pthread_mutex_lock(&g_picture_mutex);
    if (!g_picture_ready) {
        pthread_mutex_unlock(&g_picture_mutex);
        return 0;
    }
    picture_rect dirty = g_desktop_buffer[back] ? g_picture_dirty[back]
                                               : (picture_rect){0, 0, g_disp_w, g_disp_h};
    picture_rect cursor = g_desktop_buffer[back] ? g_cursor_rect[back] : (picture_rect){0};
    restore_picture_rect(surf, dirty);
    restore_picture_rect(surf, cursor);
    g_picture_dirty[back] = (picture_rect){0};
    g_drawn_blit_us = g_pending_blit_us[back];
    g_pending_blit_us[back] = 0;
    g_desktop_buffer[back] = 1;
    pthread_mutex_unlock(&g_picture_mutex);
    flush_picture_rect(surf, dirty);
    flush_picture_rect(surf, cursor);
    return 1;
}

