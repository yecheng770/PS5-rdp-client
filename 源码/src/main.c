static void home_click(input_frame *frame)
{
    if (!g_home_click) return;
    g_home_click = 0;
    int x = g_home_click_x, y = g_home_click_y;
    if (g_connection_open) {
        if (g_key_open) {
            if (!hit(x,y,333,427,12*105,4*81)) return;
            int col = (x-333)/105, row = (y-427)/81;
            if ((x-333)%105 >= 93 || (y-427)%81 >= 65) return;
            g_key_index = row*UI_KEY_COLS + col;
        } else {
            if (!hit(x,y,125,208,1670,86*UI_CONN_COUNT) || (y-208)%86 >= 64) return;
            g_connection_focus = (y-208)/86;
            if (g_connection_focus == UI_CONN_HISTORY && (x < 555 || x >= 1720)) {
                frame->left = x < 555;
                frame->right = !frame->left;
                frame->any = 1;
                return;
            }
        }
    } else if (g_language_open) {
        if (hit(x,y,UI_LANG_X,UI_LANG_LIST_Y,UI_LANG_W,UI_LANG_ROW_H*UI_LANG_COUNT)) {
            g_language_focus = (y - UI_LANG_LIST_Y) / UI_LANG_ROW_H;
        } else {
            frame->cancel = frame->any = 1;
            return;
        }
    } else if (g_custom_axis >= 0) {
        return;
    } else {
        int control;
        for (control = 0; control < UI_HOME_COUNT; ++control) {
            const ui_home_rect *r = &ui_home_controls[control];
            if (hit(x, y, r->x, r->y, r->w, r->h)) break;
        }
        if (control == UI_HOME_COUNT) return;
        g_home_focus = control;
        if (control == UI_HOME_RESOLUTION || control == UI_HOME_SCALE) {
            const ui_home_rect *r = &ui_home_controls[control];
            frame->left = x < r->x + 119;
            frame->right = x >= r->x + r->w - 121;
            if (frame->left || frame->right) { frame->any = 1; return; }
        }
    }
    frame->confirm = frame->any = 1;
}

static void menu_input(const input_frame *f)
{
    rdp_state st;
    psrdp_get_state(&st);

    if (g_connection_open) {
        if (session_alive()) g_connection_open = g_key_open = 0;
        else connection_input(f);
        if (f->any) menu_invalidate();
        return;
    }
    if (g_custom_axis >= 0) {
        int *value = g_custom_axis == 0 ? &g_custom_w : &g_custom_h;
        int min = g_custom_axis == 0 ? PSRDP_REMOTE_MIN_W : PSRDP_REMOTE_MIN_H;
        int max = g_custom_axis == 0 ? PSRDP_REMOTE_MAX_W : PSRDP_REMOTE_MAX_H;
        *value += f->right - f->left + 10 * (f->up - f->down) + 100 * (f->r1 - f->l1);
        if (*value < min) *value = min;
        if (*value > max) *value = max;
        if (f->cancel) custom_load();
        else if (f->confirm && g_custom_axis == 0) g_custom_axis = 1;
        else if (f->confirm) {
            if (!st.running) {
                g_saved_custom = 1;
                snprintf(g_cfg.res, sizeof(g_cfg.res), "%dx%d", g_custom_w, g_custom_h);
                conf_save();
            }
            g_custom_axis = -1;
        }
        if (f->any || f->l1 || f->r1) menu_invalidate();
        return;
    }

    if (g_language_open) {
        if (f->cancel) g_language_open = 0;
        else if (f->confirm) {
            int previous = g_ui_language;
            g_ui_language = g_language_focus;
            if (g_ui_language != previous && !conf_save()) g_ui_language = previous;
            g_language_open = 0;
        } else if (f->up || f->down) {
            g_language_focus = (g_language_focus + UI_LANG_COUNT + f->down - f->up) % UI_LANG_COUNT;
        }
        if (f->any) menu_invalidate();
        return;
    }
    if (f->up || f->down || (f->cancel && g_home_focus != UI_HOME_CONNECT)) {
        int next = (int)g_home_focus + f->down - f->up;
        if (f->cancel) next = UI_HOME_CONNECT;
        if (next >= 0 && next < UI_HOME_COUNT) g_home_focus = next;
        g_res_sel = g_saved_custom ? RES_COUNT : res_index(g_cfg.res);
        custom_load();
        menu_invalidate();
        return;
    }
    if (g_home_focus == UI_HOME_CONNECT) {
        if (f->confirm && !st.running) {
            session_start();
            menu_invalidate();
        }
        return;
    }
    if (g_home_focus == UI_HOME_LANGUAGE) {
        if (f->confirm) {
            g_language_open = 1;
            g_language_focus = g_ui_language;
            menu_invalidate();
        }
        return;
    }
    if (st.running) return;
    if (g_home_focus == UI_HOME_SETTINGS) {
        if (f->confirm) {
            begin_profile_edit(current_profile());
            g_connection_open = 1;
            g_connection_focus = UI_CONN_HOST;
            g_history_selected = 0;
            g_connection_message = NULL;
            menu_invalidate();
        }
        return;
    }
    if (g_home_focus == UI_HOME_SCALE) {
        int selected = 0;
        for (int i = 0; i < SCALE_COUNT; ++i)
            if (g_cfg.desktop_scale == g_scale_options[i]) selected = i;
        int next = selected + f->right - f->left;
        if (next >= 0 && next < SCALE_COUNT && next != selected) {
            g_cfg.desktop_scale = g_scale_options[next];
            conf_save();
            menu_invalidate();
        }
        return;
    }
    int next = g_res_sel + f->right - f->left;
    if (next >= 0 && next <= RES_COUNT && next != g_res_sel) {
        g_res_sel = next;
        if (next == RES_COUNT) custom_load();
        else {
            g_saved_custom = 0;
            snprintf(g_cfg.res, sizeof(g_cfg.res), "%s", g_res_options[next]);
            conf_save();
        }
        menu_invalidate();
    }
    if (f->confirm && g_res_sel == RES_COUNT) {
        g_custom_axis = 0;
        menu_invalidate();
    }
}

/* ---- live session ---- */

static void live_enter(void)
{
    g_live = 1;
    g_had_session = 1;
    g_language_open = 0;
    g_home_click = 0;
    input_set_sink(NULL);
    memset(&g_session_menu,0,sizeof(g_session_menu));
    memset(g_remote_keys,0,sizeof(g_remote_keys));
    input_set_sink(&g_remote_sink);
    g_ptr_x = g_disp_w/2;
    g_ptr_y = g_disp_h/2;
    g_ptr_acc_x = g_ptr_acc_y = g_wheel_acc = 0;
    g_buttons = 0;
    memset(g_button_hold,0,sizeof(g_button_hold));
    pointer_send();
    psrdp_note("session live: %dx%d", rdp_desktop_width(), rdp_desktop_height());
}

static void live_leave(void)
{
    remote_input_pause();
    g_live = 0;
    memset(&g_session_menu,0,sizeof(g_session_menu));
    g_home_focus = UI_HOME_CONNECT;
    g_res_sel = g_saved_custom ? RES_COUNT : res_index(g_cfg.res);
    custom_load();
    input_set_sink(&g_home_sink);
    g_buttons = 0;
    g_ptr_acc_x = g_ptr_acc_y = g_wheel_acc = 0;
    menu_invalidate();
}

static void live_input(const input_frame *f)
{
    int action=session_menu_step(&g_session_menu,f);
    if (action==SESSION_MENU_OPEN) {
        remote_input_pause();
        psrdp_note("session menu opened");
        return;
    }
    if (action==SESSION_MENU_CLOSE) {
        input_set_sink(&g_remote_sink);
        return; /* The selection press belongs only to the local menu. */
    }
    if (action==SESSION_MENU_DISCONNECT) {
        rdp_stop();
        psrdp_note("disconnect requested from session menu");
        return;
    }
    if (g_session_menu.open) return;

    input_pad_to_remote(f, &g_ptr_acc_x, &g_ptr_acc_y, &g_wheel_acc, g_disp_w, g_disp_h);

    pointer_apply_motion();
    if (g_wheel_acc) {
        rdp_send_wheel(remote_x(), remote_y(), g_wheel_acc);
        g_wheel_acc = 0;
    }
}

static void draw_session_menu(uint32_t *surf)
{
    uint32_t *lin=ui_lin_get(g_disp_w,g_disp_h);
    if (!lin) return;
    pthread_mutex_lock(&g_picture_mutex);
    size_t bytes = (size_t)g_disp_w * g_disp_h * sizeof(*lin);
    if (g_picture_ready) memcpy(lin, g_picture, bytes);
    else memset(lin, 0, bytes);
    pthread_mutex_unlock(&g_picture_mutex);
    ui_surface surface={g_disp_w,g_disp_h,g_disp_w,lin};
    ui_begin(&surface);
    ui_draw_session_menu(g_session_menu.stopping);
    present_linear(surf,lin,g_disp_w,g_disp_h);
}

