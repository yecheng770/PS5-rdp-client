static void display_size(int w, int h, int mode)
{
    g_disp_w = w;
    g_disp_h = h;
    g_tiles_per_col = (w + PS5_TILE_WIDTH - 1) / PS5_TILE_WIDTH;
    g_tile_rows = (h + PS5_TILE_HEIGHT - 1) / PS5_TILE_HEIGHT;
    g_mode = mode;
}

static size_t display_align(size_t bytes)
{
    return (bytes + DIRECT_MEM_ALIGN - 1) & ~(size_t)(DIRECT_MEM_ALIGN - 1);
}

static int display_try(int w, int h, int mode)
{
    display_size(w, h, mode);
    int base = w == BASE_DISP_W && h == BASE_DISP_H;
    size_t tiled = (size_t)g_tiles_per_col * g_tile_rows * TILE_BYTES;
    if (mode == MODE_COMPACT)
        tiled = (block_base(g_tiles_per_col - 1, g_tile_rows - 1) + PS5_TILE_SIZE)
                * sizeof(uint32_t);
    size_t stride = base ? BASE_BUF_STRIDE : display_align(tiled);
    size_t linear = base ? 0 : display_align((size_t)w * h * sizeof(uint32_t));
    size_t total = 2 * stride + 2 * linear;

    g_rc_alloc = sceKernelAllocateDirectMemory(0, INT64_C(0x400000000), total,
                                               DIRECT_MEM_ALIGN,
                                               DIRECT_MEM_TYPE, &g_dmem_off);
    if (g_rc_alloc != 0) return -1;
    g_dmem_base = NULL;
    g_rc_map = sceKernelMapDirectMemory(&g_dmem_base, total, MAP_PROTECTION, 0,
                                        g_dmem_off, DIRECT_MEM_ALIGN);
    if (g_rc_map != 0 || !g_dmem_base) {
        sceKernelReleaseDirectMemory(g_dmem_off, total);
        return -2;
    }

    uint8_t *memory = g_dmem_base;
    g_buf[0] = (uint32_t *)memory;
    g_buf[1] = (uint32_t *)(memory + stride);
    g_ui_lin = linear ? (uint32_t *)(memory + 2 * stride) : g_base_ui;
    g_picture = linear ? (uint32_t *)(memory + 2 * stride + linear) : g_base_picture;

    vo_attribute attr = {0};
    vo_buffer bufs[2] = {{0}};
    sceVideoOutSetBufferAttribute2(&attr, VO_FORMAT_SDR, 0, w, h, 0, 0, 0);
    bufs[0].data = g_buf[0];
    bufs[1].data = g_buf[1];
    g_rc_register = sceVideoOutRegisterBuffers2(g_vo, 0, 0, bufs, 2, &attr, 0, NULL);
    if (g_rc_register == 0) {
        clear_surface(g_buf[0], 0x000E1116u);
        flush_rect(g_buf[0], 0, 0, w, h);
        g_rc_flip = sceVideoOutSubmitFlip(g_vo, 0, 1, (int64_t)g_flip_arg++);
        if (g_rc_flip != 0) {
            sceVideoOutWaitVblank(g_vo);
            g_rc_flip = sceVideoOutSubmitFlip(g_vo, 0, 1, (int64_t)g_flip_arg++);
        }
        if (g_rc_flip == 0) {
            sceVideoOutWaitVblank(g_vo);
            g_front = 0;
            g_flip_ok++;
            return 0;
        }
        if (sceVideoOutUnregisterBuffers(g_vo, 0) != 0) return -6;
    }
    sceKernelReleaseDirectMemory(g_dmem_off, total);
    g_dmem_base = NULL;
    g_buf[0] = g_buf[1] = NULL;
    g_ui_lin = g_base_ui;
    g_picture = g_base_picture;
    return g_rc_register ? -4 : -5;
}

static int display_init(void)
{
    int base_mode = g_mode;
    for (int attempt = 1; attempt <= 6; ++attempt) {
        g_open_attempts = attempt;
        g_vo = sceVideoOutOpen(0xff, 0, 0, NULL);
        if (g_vo >= 0) break;
        sceKernelUsleep(500000);
    }
    g_rc_open = g_vo;
    if (g_vo < 0) return -3;

    sceVideoOutSetFlipRate(g_vo, 0);
    g_rc_output = sceVideoOutGetResolutionStatus(g_vo, &g_output);
    uint32_t w = g_output.full_width, h = g_output.full_height;
    int rc;
    if (g_rc_output == 0 && w >= 640 && h >= 480 &&
        w <= MAX_DISP_W && h <= MAX_DISP_H) {
        if (w == BASE_DISP_W && h == BASE_DISP_H)
            return display_try(BASE_DISP_W, BASE_DISP_H, base_mode);
        /* Compact rows are laid out in 128-pixel-wide groups. A partial
         * group can overlap the following row of tiles. */
        if (w % 128u != 0) {
            g_output_fallback = "unsupported scanout width";
        } else {
            rc = display_try((int)w, (int)h, MODE_COMPACT);
            if (rc == 0 || rc == -6) return rc;
            printf("[psrdp] native %ux%u refused: rc=%d alloc=%d map=%d register=%d flip=%d\n",
                   w, h, rc, g_rc_alloc, g_rc_map, g_rc_register, g_rc_flip);
            g_output_fallback = rc == -1 || rc == -2 ? "memory" :
                                rc == -4 ? "registration" : "initial flip";
        }
    } else {
        g_output_fallback = "output size unavailable or out of range";
    }
    return display_try(BASE_DISP_W, BASE_DISP_H, base_mode);
}

static int display_present(int idx)
{
    int paced = 0;
    int rc = sceVideoOutSubmitFlip(g_vo, idx, 1, (int64_t)g_flip_arg);
    if (rc != 0) {
        sceVideoOutWaitVblank(g_vo);
        rc = sceVideoOutSubmitFlip(g_vo, idx, 1, (int64_t)g_flip_arg);
    }
    g_rc_flip = rc;
    if (rc == 0) {
        g_flip_ok++;
        /* SubmitFlip only queues the switch: until the next vblank the
         * buffer we are about to draw into is still the one being scanned
         * out. Drawing into it early overwrites pixels the display is
         * reading right now - a still picture hides that completely (both
         * frames are identical), a moving one shows it as a dark band along
         * the trailing edge. */
        paced = sceVideoOutWaitVblank(g_vo) == 0;
    }
    g_flip_arg++;
    if (rc == 0)
        g_front = idx;
    return paced;
}

