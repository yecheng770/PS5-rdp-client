/* Write-back                                                          */
/*                                                                     */
/* The surface sits in direct memory the GPU scans out. Nothing in the  */
/* store path orders those stores against the GPU's reads, so without   */
/* an explicit clflush the scanout keeps picking up stale DRAM lines -  */
/* which is precisely what "layout is right but pixels linger" looks    */
/* like. Only what was touched this frame is flushed.                   */
/* ------------------------------------------------------------------ */

#define TILE_BYTES ((size_t)PS5_TILE_SIZE * 4u)

static void flush_rect(uint32_t *surf, int x, int y, int w, int h)
{
    if (w <= 0 || h <= 0)
        return;

    if (g_mode == MODE_LIN1920 || g_mode == MODE_LIN2048) {
        int pitch = (g_mode == MODE_LIN1920) ? g_disp_w : 2048;
        uint8_t *base = (uint8_t *)surf;
        for (int yy = y; yy < y + h && yy < g_disp_h; ++yy) {
            uint8_t *a = base + ((size_t)yy * (size_t)pitch + (size_t)x) * 4u;
            uint8_t *p = (uint8_t *)((uintptr_t)a & ~(uintptr_t)63);
            uint8_t *e = a + (size_t)w * 4u;
            for (; p < e; p += 64)
                __asm__ volatile("clflush (%0)" :: "r"(p) : "memory");
        }
    } else {
        int c0 = x >> 9, c1 = (x + w - 1) >> 9;
        int r0 = y >> 7, r1 = (y + h - 1) >> 7;
        for (int b = r0; b <= r1; ++b)
            for (int c = c0; c <= c1; ++c) {
                uint8_t *tp = (uint8_t *)(surf + block_base(c, b));
                for (size_t o = 0; o < TILE_BYTES; o += 64)
                    __asm__ volatile("clflush (%0)" :: "r"(tp + o) : "memory");
            }
    }
    __asm__ volatile("mfence" ::: "memory");
}

