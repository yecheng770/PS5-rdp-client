#!/usr/bin/env python3
"""Bake globe.svg's two stroked ellipses and equator into alpha masks."""
from pathlib import Path
import re
import xml.etree.ElementTree as ET
from PIL import Image, ImageDraw

folder = Path(__file__).resolve().parent
svg = ET.parse(folder / "globe.svg").getroot()
assert svg.attrib["viewBox"] == "0 0 24 24"
stroke = float(svg.attrib["stroke-width"])
header = ["/* Generated by assets/globe/render_globe.py. */"]
for side in (21, 32, 64):
    supersample = side * 8
    scale = supersample / 24
    image = Image.new("L", (supersample, supersample))
    draw = ImageDraw.Draw(image)
    for element in svg:
        tag = element.tag.rsplit("}", 1)[-1]
        a = element.attrib
        if tag in ("circle", "ellipse"):
            cx, cy = float(a["cx"]), float(a["cy"])
            rx, ry = (float(a["r"]),) * 2 if tag == "circle" else (float(a["rx"]), float(a["ry"]))
            d = stroke / 2
            bounds = (cx - rx - d, cy - ry - d, cx + rx + d, cy + ry + d)
            draw.ellipse(tuple(round(v * scale) for v in bounds), outline=255,
                         width=round(stroke * scale))
        elif tag == "path":
            x0, y, x1 = map(float, re.fullmatch(r"M([0-9.]+) ([0-9.]+)H([0-9.]+)", a["d"]).groups())
            draw.line(tuple(round(v * scale) for v in (x0, y, x1, y)), fill=255,
                      width=round(stroke * scale))
        else:
            raise ValueError(tag)
    pixels = list(image.resize((side, side), Image.Resampling.BOX).tobytes())
    header.append(f"static const unsigned char psrdp_globe_{side}[{side * side}] = {{")
    for i in range(0, len(pixels), side):
        header.append("    " + ", ".join(map(str, pixels[i:i+side])) + ",")
    header.append("};")
(folder.parents[1] / "src/psrdp_globe.inc").write_text("\n".join(header) + "\n")
