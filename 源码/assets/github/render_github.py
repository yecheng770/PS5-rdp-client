#!/usr/bin/env python3
"""Bake a GitHub mark SVG into alpha masks (12x supersample + LANCZOS).

Usage: python render_github.py [source.svg]
Bakes the three sizes (21/32/64) the UI pipeline uses into
src/psrdp_github.inc, and writes a side-by-side preview.png.
"""
from pathlib import Path
import sys
import xml.etree.ElementTree as ET
from PIL import Image, ImageDraw
from svgpathtools import parse_path

folder = Path(__file__).resolve().parent
SRC = Path(sys.argv[1]) if len(sys.argv) > 1 else folder / "github-svgrepo.svg"

doc = ET.parse(SRC).getroot()
vb = [float(v) for v in doc.attrib["viewBox"].split()]
paths = []
for elem in doc.iter():
    d = elem.attrib.get("d")
    if d:
        paths.append(parse_path(d))
POLYS = []
for p in paths:
    for sub in p.continuous_subpaths():
        pts = []
        steps = 200
        for seg in sub:
            for t in range(0, steps + 1):
                u = t / steps
                q = seg.point(u)
                pts.append((q.real - vb[0], q.imag - vb[1]))
        POLYS.append(pts)

header = [f"/* Generated by assets/github/render_github.py from {SRC.name}. */"]
for side in (21, 32, 64):
    supersample = side * 12
    scale = supersample / vb[2]
    image = Image.new("L", (supersample, supersample), 0)
    draw = ImageDraw.Draw(image)
    for pts in POLYS:
        draw.polygon([(x * scale, y * scale) for x, y in pts], fill=255, outline=255)
    down = image.resize((side, side), Image.Resampling.LANCZOS)
    pixels = list(down.tobytes())
    header.append(f"static const unsigned char psrdp_github_{side}[{side*side}] = {{")
    for i in range(0, len(pixels), side):
        header.append("    " + ", ".join(map(str, pixels[i:i+side])) + ",")
    header.append("};")

out = folder.parents[1] / "src/psrdp_github.inc"
out.write_text("\n".join(header) + "\n")
print(f"wrote {out}")

# Side-by-side preview: icon at 64px on the app's dark background.
foreground = (220, 231, 252)
background = (5, 12, 30)
iconx = Image.new("RGB", (64, 64), background)
mask = iconx  # placeholder replaced below
m = None
import re
text = out.read_text()
m32 = re.search(r"psrdp_github_32\[(\d+)\] = \{(.*?)\};", text, re.S)
mask32 = [int(x) for x in m32.group(2).replace("\n", "").split(",") if x.strip()]
mimg = Image.new("L", (32, 32), 0)
mimg.putdata(mask32)
fg = Image.new("RGB", (32, 32), foreground)
bg = Image.new("RGB", (32, 32), background)
tile = Image.composite(fg, bg, mimg).resize((128, 128), Image.Resampling.NEAREST)
sheet = Image.new("RGB", (128, 128), background)
sheet.paste(tile, (0, 0))
sheet.save(folder / "preview.png")
print(f"wrote {folder / 'preview.png'}")
