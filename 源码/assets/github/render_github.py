#!/usr/bin/env python3
"""Bake assets/github/github-svgrepo.svg (GitHub cat mark, 24x24 viewBox minus
the 0.5 bottom offset) into alpha masks — same pipeline as assets/globe.

The source icon: https://www.svgrepo.com/show/394174/github.svg
(baked here as filled path, stroke not needed).
"""
from pathlib import Path
import xml.etree.ElementTree as ET
from PIL import Image, ImageDraw
from svgpathtools import parse_path

folder = Path(__file__).resolve().parent
SVG = folder / "github-svgrepo.svg"

header = ["/* Generated by assets/github/render_github.py from svgrepo 394174 (GitHub mark). */"]
for side in (21, 32, 64):
    supersample = side * 8
    # viewBox "0 -0.5 25 25": width=height=25, y offset -0.5.
    doc = ET.parse(SVG).getroot()
    vb = [float(v) for v in doc.attrib["viewBox"].split()]
    scale = supersample / vb[2]

    polys = []
    for elem in doc.iter():
        d = elem.attrib.get("d")
        if not d:
            continue
        path = parse_path(d)
        for sub in path.continuous_subpaths():
            pts = []
            steps = 128
            for seg in sub:
                for t in range(0, steps + 1):
                    u = t / steps
                    p = seg.point(u)
                    pts.append(((p.real - vb[0]) * scale, (p.imag - vb[1]) * scale))
            polys.append(pts)

    image = Image.new("L", (supersample, supersample), 0)
    draw = ImageDraw.Draw(image)
    for pts in polys:
        draw.polygon(pts, fill=255, outline=255)
    pixels = list(image.resize((side, side), Image.Resampling.BOX).tobytes())
    header.append(f"static const unsigned char psrdp_github_{side}[{side*side}] = {{")
    for i in range(0, len(pixels), side):
        header.append("    " + ", ".join(map(str, pixels[i:i+side])) + ",")
    header.append("};")

out = folder.parents[1] / "src/psrdp_github.inc"
out.write_text("\n".join(header) + "\n")
print(f"wrote {out}")
